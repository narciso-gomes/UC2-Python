print('Informe dois números: ')
n1 = float(input('Primeiro número (n1): '))
n2 = float(input('Segundo número (n2): '))

print('')

print("# Adição (+)")
r = n1 + n2
print(n1,"+",n2,"=",r)

print('')

print("# Subtração (-)")
r = n1 - n2
print(n1,"-",n2,"=",r)

print('')


print("# Divisão (/)")
r = n1 / n2
print(n1,"/",n2,"=",r)

print('')

print("# Divisão Inteira (//)")
r = n1 // n2
print(n1,"//",n2,"=",r)

print('')

print('# Resto de Divisão (%)')
r = n1 % n2
print(n1,"%",n2,"=",r)

print('')

print('# Multiplicação (*)')
r = n1 * n2
print(n1,"*",n2,"=",r)

print('')

print('# Potenciação (**)')
r = n1 ** n2
print(n1,"**",n2,"=",r)

